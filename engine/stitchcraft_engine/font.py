GLYPH_W, GLYPH_H, GAP = 4.0, 6.0, 1.8


def layout_text(text: str, height_mm: float, spacing: float = 1.0) -> List[Stroke]:
    """Strokes in mm, y DOWN, origin at the top-left of the text block. Unknown characters are skipped."""
    k = height_mm / GLYPH_H
    x, out = 0.0, []
    for ch in text.upper():
        if ch == " ":
            x += (GLYPH_W * 0.7 + GAP) * k * spacing
            continue
        g = GLYPHS.get(ch)
        if not g:
            continue
        for st in g:
            out.append([(x + px * k, (GLYPH_H - py) * k) for px, py in st])
        x += (GLYPH_W + GAP) * k * spacing
    return out


def text_width(text: str, height_mm: float, spacing: float = 1.0) -> float:
    k = height_mm / GLYPH_H
    w = 0.0
    for ch in text.upper():
        w += ((GLYPH_W * 0.7 if ch == " " else GLYPH_W) + GAP) * k * spacing
    return max(w - GAP * k * spacing, 0.0)
